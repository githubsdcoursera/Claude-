#!/usr/bin/env python3
"""Build towerco-data.js (the mock prelude) from the synthetic Tower Co CSVs.

The supplied package has the joined reconciliation view, one agreement and the golden tests. The
site/order/EB/document/dispute objects the blueprint lists (sites.csv, orders.csv, eb_bills.csv,
disputes.csv) were not supplied, so the minimum Digital Twin is derived here from the labelled
expected values, plus three clearly marked fixtures needed by golden tests GOLD-002, GOLD-004, GOLD-005.
"""
import csv, json, pathlib
D = pathlib.Path(__file__).parent
rows = list(csv.DictReader(open(D / "reconciliation.csv")))
agr = list(csv.DictReader(open(D / "agreements.csv")))[0]
periods = sorted({r["billing_period"] for r in rows})
sites = {}
for r in rows:
    s = sites.setdefault(r["site_id"], {"eb": {}, "rent_zero": [], "clt_qty": None})
    exp = float(r["expected_amount_inr"])
    if r["component"] == "RENT" and exp == 0: s["rent_zero"].append(r["billing_period"])
    if r["component"] == "LOADING" and exp > 0: s["clt_qty"] = round(exp / float(agr["loading_rate_per_unit_inr"]))
    if r["component"] == "ENERGY_EB": s["eb"][r["billing_period"]] = exp
twin = {}
for sid, s in sorted(sites.items()):
    n = int(sid[-4:])
    z = s["rent_zero"]
    t = {"rfs": "2025-04-01", "exit": None, "non_bts_from": None, "clt_qty": s["clt_qty"], "consumer": "CONS-SYN-%05d" % n,
         "eb": [s["eb"][p] for p in periods], "circle": "MH-GOA", "landlord": "LL-SYN-%04d" % n}
    if z and z[0] == periods[0]:          # zero expected rent from the first period: RFS after it (premature-billing site)
        t["rfs"] = next(p for p in periods if p not in z) + "-01"
    elif z:                               # zero expected rent from a later period: exited or non-BTS
        nonbts = any(r["site_id"] == sid and r["scenario_label"] == "NON_BTS_BILLING" for r in rows)
        last_active = periods[periods.index(z[0]) - 1]
        if nonbts: t["non_bts_from"] = z[0] + "-01"
        else: t["exit"] = last_active + "-31"
    if t["clt_qty"] is None: t["clt_qty"] = int(next(r["quantity"] for r in rows if r["site_id"] == sid and r["component"] == "LOADING"))
    twin[sid] = t
# ---- Fixtures (not in the supplied CSV) ----
twin["MHGOA-SYN-0024"]["consumer"] = "CONS-SYN-00014"      # GOLD-004: one EB consumer number mapped to two sites
docs_missing = {"MHGOA-SYN-0005|2026-06": ["EB bill copy", "loading annexure"]}   # GOLD-005
comp = {"RENT": 0, "LOADING": 1, "ENERGY_EB": 2}
lines = [[r["invoice_line_id"][-7:], r["invoice_id"][-6:], int(r["site_id"][-4:]), comp[r["component"]], periods.index(r["billing_period"]),
          float(r["quantity"]), float(r["rate_inr"]), float(r["line_amount_inr"]), r["scenario_label"], float(r["expected_amount_inr"]),
          r["expected_classification"]] for r in rows]
lines.append(["0000541", "000181", 2, 0, 0, 1.0, 52500.0, 52500.0, "DUPLICATE_LINE", 0.0, "DUPLICATE"])  # GOLD-002 fixture
disputes = [{"id": "DSP-SYN-0001", "site": "MHGOA-SYN-0007", "period": "2026-08", "component": "RENT", "status": "OPEN", "control_no": "CTRL-SYN-0001", "amount": 52500}]
T = {"agreement": {"id": agr["agreement_id"], "tower_company": agr["tower_company"], "version": agr["version"], "effective_from": agr["effective_from"],
       "effective_to": agr["effective_to"], "base_rent": float(agr["base_rent_monthly_inr"]), "escalation_pct": float(agr["annual_escalation_pct"]),
       "anniversary": agr["escalation_anniversary"], "loading_rate": float(agr["loading_rate_per_unit_inr"]), "fem_rate": float(agr["fem_rate_monthly_inr"]),
       "payment_terms_days": int(agr["payment_terms_days"])},
     "periods": periods, "sites": twin, "lines": lines, "docs_missing": docs_missing, "disputes": disputes}
js = (D / "engine.js").read_text()
out = ("// SYNTHETIC DATA ONLY: generated by data/build_data.py from the supplied Tower Co synthetic package.\n"
       "// Not Vi actuals, vendor claims, contractual terms or accounting evidence.\n"
       "const T = " + json.dumps(T, separators=(",", ":")) + ";\n" + js)
(D.parent / "towerco-data.js").write_text(out)
print("sites", len(twin), "lines", len(lines), "bytes", len(out))
